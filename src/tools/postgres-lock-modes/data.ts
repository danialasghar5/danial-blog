// Operations and the table-level locks they take. Every entry cites the
// PostgreSQL 17 docs page it was checked against (`source`); the matrix itself
// lives in ../_shared/pg-locks.ts. Versions: the lock modes are unchanged across
// Postgres 13–17 (TOOLS_ROADMAP.md A4: re-verify per major).
import type { LockMode } from '../_shared/pg-locks.ts';

export type LockObject = 'table' | 'referenced table' | 'index';

export interface OperationLock {
	object: LockObject;
	mode: LockMode;
}

export interface Operation {
	id: string;
	label: string;
	kind: 'sql' | 'rails';
	/** For Rails methods: the id of the SQL operation they emit. */
	sqlEquivalent?: string;
	locks: OperationLock[];
	pgVersions: string;
	notes: string;
	saferAlternative?: string;
	aliases: string[];
	source: string;
}

